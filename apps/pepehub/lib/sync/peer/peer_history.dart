/// Local retention policy. It is deliberately absent from the peer protocol.
class PeerHistorySettings {
  final bool enabled;
  final int maxDays, maxBytes;
  const PeerHistorySettings({
    this.enabled = false,
    this.maxDays = 30,
    this.maxBytes = 500 * 1024 * 1024,
  });
  void validate() {
    if (maxDays < 1 || maxDays > 3650 || maxBytes < 1 || maxBytes > 1 << 40) {
      throw ArgumentError('Некорректные ограничения истории');
    }
  }

  Map<String, dynamic> toJson() => {
    'enabled': enabled,
    'maxDays': maxDays,
    'maxBytes': maxBytes,
  };
  factory PeerHistorySettings.fromJson(dynamic value) {
    if (value is! Map) return const PeerHistorySettings();
    final days = value['maxDays'], bytes = value['maxBytes'];
    return PeerHistorySettings(
      enabled: value['enabled'] == true,
      maxDays: days is int && days >= 1 && days <= 3650 ? days : 30,
      maxBytes: bytes is int && bytes >= 1 && bytes <= 1 << 40
          ? bytes
          : 500 * 1024 * 1024,
    );
  }
}

/// Only names generated by PepeHub are eligible for retention or deletion.
DateTime? peerHistoryTime(String name) {
  for (final pattern in [
    RegExp(r'^v1-(\d{13})-[a-f0-9]{32}-.+$'),
    RegExp(r'^\.pepehub-version-(\d{13})-[a-f0-9]{8}-.+$'),
    RegExp(r'^(\d{16})-[a-f0-9]{12}-.+$'),
  ]) {
    final match = pattern.firstMatch(name);
    if (match != null) {
      final value = int.parse(match[1]!);
      return DateTime.fromMillisecondsSinceEpoch(
        match[1]!.length == 16 ? value ~/ 1000 : value,
        isUtc: true,
      );
    }
  }
  return null;
}

class PeerHistorySummary {
  final int files, bytes, legacy, unknown, moved, removed, reclaimed;
  final List<String> warnings;
  const PeerHistorySummary({
    this.files = 0,
    this.bytes = 0,
    this.legacy = 0,
    this.unknown = 0,
    this.moved = 0,
    this.removed = 0,
    this.reclaimed = 0,
    this.warnings = const [],
  });
  factory PeerHistorySummary.fromJson(Map value) => PeerHistorySummary(
    files: (value['files'] as num?)?.toInt() ?? 0,
    bytes: (value['bytes'] as num?)?.toInt() ?? 0,
    legacy: (value['legacy'] as num?)?.toInt() ?? 0,
    unknown: (value['unknown'] as num?)?.toInt() ?? 0,
    moved: (value['moved'] as num?)?.toInt() ?? 0,
    removed: (value['removed'] as num?)?.toInt() ?? 0,
    reclaimed: (value['reclaimed'] as num?)?.toInt() ?? 0,
    warnings: (value['warnings'] as List? ?? const []).cast<String>(),
  );
}

abstract interface class PeerHistoryStorage {
  Future<PeerHistorySummary> maintainHistory({
    bool migrate = false,
    bool prune = false,
    bool clear = false,
  });
}
